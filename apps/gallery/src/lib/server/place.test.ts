import { describe, expect, it } from 'vitest';
import { parsePlace } from './place';

// 样本全部取自线上 image.location
describe('parsePlace', () => {
	it.each([
		['广东省深圳市南山区粤海街道深南大道9688号深圳万象天地', '深圳市', '广东省'],
		['四川省甘孜藏族自治州道孚县鲜水镇解放西街128号', '道孚县', '四川省 甘孜藏族自治州'],
		['青海省海西蒙古族藏族自治州格尔木市昆仑路街道柴达木中路', '格尔木市', '青海省 海西蒙古族藏族自治州'],
		['青海省海西蒙古族藏族自治州海西蒙古族藏族自治州直辖柴旦镇冷乌线', '海西蒙古族藏族自治州', '青海省'],
		['新疆维吾尔自治区喀什地区喀什市吾斯塘博依街道', '喀什市', '新疆维吾尔自治区 喀什地区'],
		['新疆维吾尔自治区克拉玛依市乌尔禾区柳树街街道中心路', '克拉玛依市', '新疆维吾尔自治区'],
		['云南省迪庆藏族自治州维西傈僳族自治县叶枝镇未来城商务酒店', '维西傈僳族自治县', '云南省 迪庆藏族自治州'],
		['日本, 〒381-2217 長野県長野市稲里町中央４丁目９番１６号', '長野市', '長野県'],
		['日本, 〒969-3285 福島県耶麻郡猪苗代町翁沢御殿山９２３番地２', '耶麻郡猪苗代町', '福島県'],
		['27 襄陽路, 100, 中正區, 臺北市, 台湾', '臺北市', '台湾'],
		['台湾桃園市', '桃園市', '台湾']
	])('%s', (address, name, region) => {
		expect(parsePlace(address)).toEqual({ name, region });
	});

	it('treats missing GPS as no place', () => {
		expect(parsePlace('No GPS data')).toBeNull();
		expect(parsePlace(null)).toBeNull();
	});
});
